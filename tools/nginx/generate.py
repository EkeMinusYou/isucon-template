#!/usr/bin/env python3
"""Render common and role-based nginx files for the topology owned by Taskfile."""
import argparse
import ipaddress
import json
import os
from pathlib import Path
import re
import shutil
import tempfile

NAME = re.compile(r"[A-Za-z0-9][A-Za-z0-9_.-]*\Z")
PATH = re.compile(r"/[A-Za-z0-9_./-]+\Z")
TOKEN = re.compile(r"@@[A-Z_]+@@")


def names(value, label):
    if not isinstance(value, list) or not value or any(
        not isinstance(item, str) or not NAME.fullmatch(item) for item in value
    ) or len(set(value)) != len(value):
        raise ValueError(f"{label} must be a nonempty list of unique host names")
    return value


def port(value):
    text = str(value)
    if not text.isdigit() or not 1 <= int(text) <= 65535:
        raise ValueError(f"invalid port: {value}")
    return text


def absolute_path(value):
    if not PATH.fullmatch(value) or ".." in Path(value).parts:
        raise ValueError(f"invalid nginx path: {value}")
    return value


def overlay(source, destination, values):
    if not source.is_dir():
        raise ValueError(f"missing nginx source directory: {source}")
    for path in sorted(source.rglob("*")):
        if path.is_symlink():
            raise ValueError(f"nginx source must not contain symlinks: {path}")
        if not path.is_file():
            continue
        output = destination / path.relative_to(source)
        content = path.read_text()
        for key, value in values.items():
            content = content.replace(f"@@{key}@@", value)
        if TOKEN.search(content):
            raise ValueError(f"unknown placeholder in {path}")
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(content)


def generate(source, output, *, all_hosts, nginx_hosts, app_hosts, traffic_hosts,
             addresses, host_config, app_port, nginx_port, static_root, access_log, tls_port=443):
    all_hosts = names(all_hosts, "ALL_HOSTS")
    nginx_hosts = names(nginx_hosts, "NGINX_HOSTS")
    app_hosts = names(app_hosts, "APP_HOSTS")
    traffic_hosts = names(traffic_hosts, "APP_TRAFFIC_HOSTS")
    if not set(nginx_hosts + app_hosts) <= set(all_hosts):
        raise ValueError("nginx and app hosts must belong to ALL_HOSTS")
    if not set(traffic_hosts) <= set(app_hosts):
        raise ValueError("APP_TRAFFIC_HOSTS must belong to APP_HOSTS")
    if not isinstance(host_config, dict) or not set(host_config) <= set(nginx_hosts):
        raise ValueError("NGINX_HOST_CONFIG keys must belong to NGINX_HOSTS")
    app_port, nginx_port, tls_port = port(app_port), port(nginx_port), port(tls_port)
    values = {"NGINX_PORT": nginx_port, "ACCESS_LOG_PATH": absolute_path(access_log)}
    static_root = absolute_path(static_root)
    source, output = Path(source).resolve(), Path(output).resolve()
    if source == output or source in output.parents or output in source.parents:
        raise ValueError("nginx source and generated output must be separate trees")
    output.parent.mkdir(parents=True, exist_ok=True)
    # Build the complete next topology before replacing any existing output.
    with tempfile.TemporaryDirectory(prefix=".nginx-", dir=output.parent) as temporary:
        stage = Path(temporary) / "nginx"
        for host in nginx_hosts:
            config = host_config.get(host, {})
            if not isinstance(config, dict) or set(config) - {"role", "app_hosts", "listen_port", "tls_port"}:
                raise ValueError(f"invalid nginx options for {host}")
            role = config.get("role", "edge")
            if not isinstance(role, str) or not NAME.fullmatch(role):
                raise ValueError(f"invalid nginx role for {host}")
            backends = names(config.get("app_hosts", traffic_hosts), f"{host}.app_hosts")
            if not set(backends) <= set(app_hosts):
                raise ValueError(f"{host} upstream hosts must belong to APP_HOSTS")
            listen_port = port(config.get("listen_port", nginx_port))
            host_values = dict(values, NGINX_PORT=listen_port, TLS_PORT=port(config.get("tls_port", tls_port)))
            destination = stage / host
            overlay(source / "common", destination, host_values)
            overlay(source / "roles" / role, destination, host_values)
            if not (destination / "nginx.conf").is_file():
                raise ValueError(f"nginx.conf missing for {host}")
            upstream = ["# GENERATED by task gen; do not edit", "upstream app {"]
            probes = ["set -eu", "sudo nginx -t",
                      f"timeout 2 bash -c '</dev/tcp/127.0.0.1/{listen_port}'"]
            for backend in backends:
                address = ipaddress.ip_address(addresses[backend])
                target = f"[{address}]" if address.version == 6 else str(address)
                upstream.append(f"  server {target}:{app_port};")
                probes.append(f"timeout 2 bash -c '</dev/tcp/{address}/{app_port}'")
            upstream += ["  keepalive 1024;", "  keepalive_requests 100000;", "}"]
            (destination / "conf.d").mkdir(exist_ok=True)
            (destination / "conf.d/upstream.conf").write_text("\n".join(upstream) + "\n")
            (destination / "snippets").mkdir(exist_ok=True)
            (destination / "snippets/static-root.conf").write_text(f"root {static_root};\n")
            (stage / "_checks").mkdir(exist_ok=True)
            (stage / "_checks" / f"{host}.sh").write_text("\n".join(probes) + "\n")
        if output.exists():
            shutil.rmtree(output)
        stage.rename(output)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", default="nginx")
    parser.add_argument("--output", default="generated/nginx")
    args = parser.parse_args()
    try:
        generate(args.source, args.output,
                 all_hosts=os.environ["ISUCON_ALL_HOSTS"].split(),
                 nginx_hosts=os.environ["ISUCON_NGINX_HOSTS"].split(),
                 app_hosts=os.environ["ISUCON_APP_HOSTS"].split(),
                 traffic_hosts=os.environ["ISUCON_APP_TRAFFIC_HOSTS"].split(),
                 addresses=json.loads(os.environ["ISUCON_HOST_ADDRESSES"]),
                 host_config=json.loads(os.environ.get("ISUCON_NGINX_HOST_CONFIG", "{}")),
                 app_port=os.environ["ISUCON_APP_PORT"],
                 nginx_port=os.environ["ISUCON_NGINX_PORT"],
                 tls_port=os.environ.get("ISUCON_NGINX_TLS_PORT", "443"),
                 static_root=os.environ["ISUCON_STATIC_ROOT"],
                 access_log=os.environ["ISUCON_ACCESS_LOG_PATH"])
    except (ValueError, KeyError, OSError) as error:
        parser.exit(1, f"nginx generation failed: {error}\n")


if __name__ == "__main__":
    main()
